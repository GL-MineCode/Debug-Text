#include "HeaderEmitter.hpp"

#include <cstdio>
#include <cstring>
#include <filesystem>

namespace {

//! 把 FontID 转成合法的 C++ 标识符
std::string makeIdentifier(const std::string& id) {
    std::string result;
    result.reserve(id.size());
    for (char ch : id) {
        const bool ok = (ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') || (ch >= '0' && ch <= '9');
        result.push_back(ok ? ch : '_');
    }
    if (result.empty() || (result[0] >= '0' && result[0] <= '9')) result.insert(result.begin(), '_');
    return result;
}

//! 转义成 C++ 字符串字面量内容（保留 UTF-8 字节原样）
std::string escapeString(const std::string& text) {
    std::string out;
    out.reserve(text.size() + 8);
    for (char ch : text) {
        switch (ch) {
        case '\\': out += "\\\\"; break;
        case '"':  out += "\\\""; break;
        case '\n': out += "\\n"; break;
        case '\r': out += "\\r"; break;
        case '\t': out += "\\t"; break;
        default:
            if (static_cast<unsigned char>(ch) < 0x20u) {
                char buffer[8];
                std::snprintf(buffer, sizeof(buffer), "\\%03o", static_cast<unsigned char>(ch));
                out += buffer;
            } else {
                out.push_back(ch);
            }
            break;
        }
    }
    return out;
}

void appendU32Array(std::string& out, const char* name, const std::vector<uint32_t>& values) {
    out += "inline constexpr std::uint32_t ";
    out += name;
    out += "[] = {\n";
    if (values.empty()) {
        out += "    0u\n";
    } else {
        for (size_t i = 0; i < values.size(); ++i) {
            if ((i % 12u) == 0u) out += "    ";
            char buffer[16];
            std::snprintf(buffer, sizeof(buffer), "0x%08Xu", values[i]);
            out += buffer;
            if (i + 1u == values.size()) {
                out += "\n";
            } else if ((i % 12u) == 11u) {
                out += ",\n";
            } else {
                out += ", ";
            }
        }
    }
    out += "};\n\n";
}

void appendU16Array(std::string& out, const char* name, const std::vector<uint16_t>& values) {
    out += "inline constexpr std::uint16_t ";
    out += name;
    out += "[] = {\n";
    if (values.empty()) {
        out += "    0u\n";
    } else {
        for (size_t i = 0; i < values.size(); ++i) {
            if ((i % 16u) == 0u) out += "    ";
            char buffer[16];
            std::snprintf(buffer, sizeof(buffer), "0x%04Xu", static_cast<unsigned>(values[i]));
            out += buffer;
            if (i + 1u == values.size()) {
                out += "\n";
            } else if ((i % 16u) == 15u) {
                out += ",\n";
            } else {
                out += ", ";
            }
        }
    }
    out += "};\n\n";
}

void appendScalar(std::string& out, const char* field, const std::string& literal) {
    out += "    font.";
    out += field;
    out += " = ";
    out += literal;
    out += ";\n";
}

void appendNumber(std::string& out, const char* field, uint64_t value) {
    char buffer[32];
    std::snprintf(buffer, sizeof(buffer), "%llu", static_cast<unsigned long long>(value));
    appendScalar(out, field, buffer);
}

void appendText(std::string& out, const char* field, const std::string& text) {
    appendScalar(out, field, "\"" + escapeString(text) + "\"");
}

} // namespace

bool emitFontHeader(PackedFont& font, const std::string& outputPath, std::string& error, bool& changed) {
    changed = false;

    const std::string identifier = makeIdentifier(font.id);
    std::string out;
    out.reserve(font.atlas.size() * 13u + 65536u);

    out += "#pragma once\n";
    out += "// ============================================================================\n";
    out += "// AUTO-GENERATED by DebugText generator (font format v2) -- DO NOT EDIT\n";
    out += "// FontID : " + font.id + "\n";
    out += "// Family : " + font.displayName + " / " + font.styleName + "\n";
    out += "// Source : " + font.sourceFile + " " + font.sourceVersion + "\n";
    out += "// License: " + font.licenseName + "\n";
    if (!font.copyright.empty()) out += "//          " + font.copyright + "\n";
    out += "// ============================================================================\n\n";
    out += "#include <cstdint>\n\n";
    out += "#include \"DebugText.hpp\"\n\n";
    out += "namespace dbtext::fonts::" + identifier + " {\n\n";

    appendU32Array(out, "kPresenceBits", font.presenceBits);
    appendU32Array(out, "kPresenceBlocks", font.presenceBlocks);
    appendU32Array(out, "kFullWidthBits", font.fullWidthBits);
    appendU32Array(out, "kFullWidthBlocks", font.fullWidthBlocks);
    appendU32Array(out, "kAtlas", font.atlas);
    appendU32Array(out, "kExtraBits", font.extraBits);
    appendU32Array(out, "kExtraBlocks", font.extraBlocks);
    appendU16Array(out, "kExtraDims", font.extraDims);
    appendU32Array(out, "kExtraOffsets", font.extraOffsets);
    appendU32Array(out, "kExtraData", font.extraData);

    out += "inline constexpr FontDesc makeFont() noexcept {\n";
    out += "    FontDesc font{};\n";
    out += "    font.formatVersion = kFontFormatVersion;\n";
    appendNumber(out, "flags", 1u);
    appendText(out, "id", font.id);
    appendText(out, "displayName", font.displayName);
    appendText(out, "styleName", font.styleName);
    appendText(out, "copyright", font.copyright);
    appendText(out, "licenseName", font.licenseName);
    appendText(out, "sourceFile", font.sourceFile);
    appendText(out, "sourceVersion", font.sourceVersion);
    appendNumber(out, "cellWidth", font.cellWidth);
    appendNumber(out, "cellHeight", font.cellHeight);
    appendNumber(out, "halfWidth", font.halfWidth);
    appendNumber(out, "tabWidth", font.tabWidth);
    appendNumber(out, "maxCodepoint", font.maxCodepoint);
    appendNumber(out, "glyphCount", font.glyphCount);
    appendNumber(out, "presenceWordCount", font.presenceBits.size());
    appendScalar(out, "presenceBits", "kPresenceBits");
    appendScalar(out, "presenceBlockCounts", "kPresenceBlocks");
    appendNumber(out, "fullWidthWordCount", font.fullWidthBits.size());
    appendScalar(out, "fullWidthBits", "kFullWidthBits");
    appendScalar(out, "fullWidthBlockCounts", "kFullWidthBlocks");
    appendNumber(out, "halfRecordBytes", font.halfRecordBytes);
    appendNumber(out, "fullRecordBytes", font.fullRecordBytes);
    appendScalar(out, "atlas", "kAtlas");
    appendNumber(out, "extraCount", font.extraCount);
    appendScalar(out, "extraBits", "kExtraBits");
    appendScalar(out, "extraBlockCounts", "kExtraBlocks");
    appendScalar(out, "extraDims", "kExtraDims");
    appendScalar(out, "extraOffsets", "kExtraOffsets");
    appendScalar(out, "extraData", "kExtraData");
    out += "    return font;\n";
    out += "}\n\n";

    out += "inline constexpr FontDesc kFont = makeFont();\n";
    out += "inline const AutoRegister kAutoRegister{ kFont };\n\n";
    out += "} // namespace dbtext::fonts::" + identifier + "\n";

    font.headerBytes = out.size();

    // 内容未变化就不改写文件，避免无谓的重新编译
    std::FILE* existing = std::fopen(outputPath.c_str(), "rb");
    if (existing != nullptr) {
        std::string previous;
        char buffer[65536];
        size_t read = 0;
        while ((read = std::fread(buffer, 1, sizeof(buffer), existing)) > 0) previous.append(buffer, read);
        std::fclose(existing);
        if (previous == out) return true;
    }

    std::error_code code;
    const std::filesystem::path path(outputPath);
    if (path.has_parent_path()) {
        std::filesystem::create_directories(path.parent_path(), code);
    }

    std::FILE* file = std::fopen(outputPath.c_str(), "wb");
    if (file == nullptr) {
        error = "无法写入文件 " + outputPath;
        return false;
    }
    const size_t written = std::fwrite(out.data(), 1, out.size(), file);
    std::fclose(file);

    if (written != out.size()) {
        error = "写入文件不完整 " + outputPath;
        return false;
    }

    changed = true;
    return true;
}
